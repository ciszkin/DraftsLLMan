package by.ciszkin.draftsllman.coordination

import by.ciszkin.draftsllman.draftsman.Component
import by.ciszkin.draftsllman.scene.Anchor
import by.ciszkin.draftsllman.scene.BezierPath
import by.ciszkin.draftsllman.scene.CanvasSpec
import by.ciszkin.draftsllman.scene.CircleNode
import by.ciszkin.draftsllman.scene.CurveNode
import by.ciszkin.draftsllman.scene.GroupNode
import by.ciszkin.draftsllman.scene.LineNode
import by.ciszkin.draftsllman.scene.ResolvedBox
import by.ciszkin.draftsllman.scene.SceneNode
import by.ciszkin.draftsllman.scene.ShapeNode
import by.ciszkin.draftsllman.scene.Style
import by.ciszkin.draftsllman.solver.ConstraintSet
import by.ciszkin.draftsllman.solver.SceneConstraint
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class ComponentMergeTest {
    private fun circle(id: String, x: Double, y: Double) =
        CircleNode(id, "role", ResolvedBox(x, y, 10.0, 10.0), Style())

    private fun component(briefId: String, regionX: Double, regionY: Double, vararg nodes: SceneNode) =
        Component(briefId, ResolvedBox(regionX, regionY, 100.0, 100.0), nodes.associateBy { it.id }, ConstraintSet.EMPTY)

    @Test fun `offsets each component's nodes by its region and namespaces ids`() {
        val graph = merge(listOf(
            component("a", 0.0, 0.0, circle("n1", 5.0, 5.0)),
            component("b", 100.0, 200.0, circle("n1", 5.0, 5.0)), // same local id, different component
        ), CanvasSpec(500.0, 500.0))

        // a: local (5,5) + region (0,0) -> (5,5); id a__n1
        assertEquals(ResolvedBox(5.0, 5.0, 10.0, 10.0), graph.nodes["a__n1"]?.box)
        // b: local (5,5) + region (100,200) -> (105,205); id b__n1 (no collision)
        assertEquals(ResolvedBox(105.0, 205.0, 10.0, 10.0), graph.nodes["b__n1"]?.box)
        assertEquals(2, graph.nodes.size)
    }

    @Test fun `group children are remapped and excluded from rootIds`() {
        val graph = merge(listOf(
            component("a", 10.0, 20.0,
                GroupNode("g", "group", listOf("c1", "c2")),
                circle("c1", 0.0, 0.0),
                circle("c2", 0.0, 0.0),
            ),
        ), CanvasSpec(100.0, 100.0))

        assertEquals(listOf("a__c1", "a__c2"), graph.children["a__g"])
        assertEquals(listOf("a__g"), graph.rootIds, "rootIds must contain only the group, not its children")
    }

    @Test fun `empty component list yields an empty graph with the canvas`() {
        val graph = merge(emptyList(), CanvasSpec(50.0, 50.0))

        assertTrue(graph.nodes.isEmpty())
        assertEquals(CanvasSpec(50.0, 50.0), graph.canvas)
    }

    @Test fun `a stale group child id is skipped, not crashed`() {
        val graph = merge(listOf(
            component("a", 0.0, 0.0,
                GroupNode("g", "group", listOf("real", "ghost")), // "ghost" not in nodes
                circle("real", 0.0, 0.0),
            ),
        ), CanvasSpec(100.0, 100.0))

        assertEquals(listOf("a__real"), graph.children["a__g"], "the stale child id is dropped")
    }

    @Test fun `constraints are dropped even when a component carries them`() {
        val withConstraints = Component(
            "a", ResolvedBox(0.0, 0.0, 100.0, 100.0),
            mapOf("n1" to circle("n1", 0.0, 0.0)),
            ConstraintSet(listOf(SceneConstraint.Align("c1", "n1", Anchor.LEFT, "n1", Anchor.LEFT))),
        )
        val graph = merge(listOf(withConstraints), CanvasSpec(100.0, 100.0))

        assertTrue(graph.constraints.constraints.isEmpty(), "merge must drop component constraints")
    }

    /**
     * Detail nodes (line / curve / shape) generated by `add_nodes` carry explicit points/control
     * points/endpoints. Curve/Shape `withBox` is a pure translate of those points; Line `withBox` is an
     * affine box-map that degenerates to a translate for same-size boxes — and merge only ever passes
     * `node.box.translate(...)` — so a region offset applied by [merge] MUST land every detail point at
     * local + (region.x, region.y). This is the offset-merge guarantee the path relies on (and a
     * regression guard for the "detail lands at (0,0)" defect class).
     */
    @Test fun `detail nodes line curve shape translate by the region offset on merge`() {
        val localLine = LineNode("line1", "spoke", start = Pair(0.0, 0.0), end = Pair(10.0, 0.0))
        val localCurve = CurveNode(
            "curve1", "rib",
            path = BezierPath(
                startPoint = Pair(0.0, 0.0),
                endPoint = Pair(5.0, 5.0),
                controlPoint1 = Pair(2.0, 0.0),
                tension = 0.5,
            ),
        )
        val localShape = ShapeNode(
            "shape1", "stud",
            points = listOf(Pair(0.0, 0.0), Pair(2.0, 0.0), Pair(2.0, 2.0)),
        )
        // Region offset (300, 200) — a globally-solved component's top-left.
        val comp = Component(
            "w", ResolvedBox(300.0, 200.0, 80.0, 80.0),
            mapOf("line1" to localLine, "curve1" to localCurve, "shape1" to localShape),
            ConstraintSet.EMPTY,
        )

        val graph = merge(listOf(comp), CanvasSpec(500.0, 500.0))

        val line = graph.nodes["w__line1"] as LineNode
        assertEquals(Pair(300.0, 200.0), line.start, "line start must translate by region")
        assertEquals(Pair(310.0, 200.0), line.end, "line end must translate by region")

        val curve = graph.nodes["w__curve1"] as CurveNode
        assertEquals(Pair(300.0, 200.0), curve.path.startPoint, "curve start must translate")
        assertEquals(Pair(305.0, 205.0), curve.path.endPoint, "curve end must translate")
        assertEquals(Pair(302.0, 200.0), curve.path.controlPoint1, "curve control must translate")

        val shape = graph.nodes["w__shape1"] as ShapeNode
        assertEquals(
            listOf(Pair(300.0, 200.0), Pair(302.0, 200.0), Pair(302.0, 202.0)),
            shape.points,
            "every shape point must translate by region",
        )
    }
}
